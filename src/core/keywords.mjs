/**
 * 对一条内容跑全部规则。
 * 标签：标题跑全量规则 → 标题命中即打标；正文仅用 BODY_TAG_RULES 补充，
 *       避免「免试攻读」「课程建设」这类正文噪音污染标签。
 * @param {string} title
 * @param {string} [body]
 */
export function analyze(title, body = '') {
  const t = String(title || '');
  const b = String(body || '').slice(0, 4000);
  const tags = [];
  const push = (x) => { if (!tags.includes(x)) tags.push(x); };

  for (const { tag, re, notBefore, bodyOnly } of TAG_RULES) {
    if (bodyOnly) continue; // 正文专属规则下移到 BODY 阶段处理
    if (re.test(t) && !(notBefore && notBefore.test(t))) push(tag);
  }
  // 正文补充：标题未给出该标签时，用正文规则（含 bodyOnly 的长词规则）判断
  const bodyRules = [...BODY_TAG_RULES, ...TAG_RULES.filter((r) => r.bodyOnly)];
  for (const { tag, re } of bodyRules) {
    if (!tags.includes(tag) && re.test(b)) push(tag);
  }

  const audiences = [];
  for (const { audience, re } of AUDIENCE_RULES) {
    if (re.test(t) || re.test(b)) audiences.push(audience);
  }
  // 收文对象：只看正文开头的公文抬头，避免「各学院」出现在句中就误判为全体学生
  if (!audiences.includes('全体学生')) {
    for (const { audience, re } of BODY_AUDIENCE_RULES) {
      if (re.test(b)) audiences.push(audience);
    }
  }

  // 重要性只看标题（正文里的「截止」多为流程描述，不能当紧急）
  const important = IMPORTANT_RULES.some((re) => re.test(t))
    || /(截止|截至)\s*(时间|日期)/.test(t);

  return { tags, audiences, important };
}

/**
 * 生成摘要：跳过「各学院：」这类公文抬头，取正文前若干字
 */
export function makeSummary(bodyText, maxLen = 160) {
  if (!bodyText) return '';
  const clean = bodyText
    .replace(/^(各学院|各单位|全校各单位|各部门|校属各单位|各处室|各位同学|亲爱的同学们)\s*[:：]?\s*/, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (clean.length <= maxLen) return clean;
  return `${clean.slice(0, maxLen)}…`;
}

/**
 * 从标题/正文推断二级分类（用于同一大类内的细分）。
 */
export function inferSubcategory(title = '') {
  const t = title;
  if (/选课|预选|正选|补退选/.test(t)) return '选课';
  if (/考试|补考|缓考|考场/.test(t)) return '考试';
  if (/竞赛|大赛|挑战杯/.test(t)) return '竞赛';
  if (/奖学金|助学金|评奖|评优/.test(t)) return '奖助';
  if (/党课|党员|党支部|党建/.test(t)) return '党建';
  if (/招聘|就业|求职|实习/.test(t)) return '就业';
  if (/讲座|论坛|报告/.test(t)) return '讲座';
  if (/公示/.test(t)) return '公示';
  if (/通知$/.test(t)) return '通知';
  return '';
}
